SELECT COUNT(*) AS wallet_assets FROM wallet_asset;
SELECT id, UNIX_TIMESTAMP(captured_at) AS cap_epoch
FROM wallet_snapshot
WHERE captured_at BETWEEN FROM_UNIXTIME(1791741300) AND FROM_UNIXTIME(1791741615)
   OR captured_at BETWEEN FROM_UNIXTIME(1791747600) AND FROM_UNIXTIME(1791747820)
   OR captured_at BETWEEN FROM_UNIXTIME(1791778540) AND FROM_UNIXTIME(1791778550)
   OR captured_at BETWEEN FROM_UNIXTIME(1791788715) AND FROM_UNIXTIME(1791788725)
ORDER BY captured_at LIMIT 60;